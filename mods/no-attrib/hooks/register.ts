import type { Register } from 'claude-code'

const CUT = [
  /^[ \t]*Co-Authored-By: Claude[^\n"']*\n?/gim,
  /^[ \t]*Claude-Session:[^\n"']*\n?/gim,
  /^[ \t]*🤖 Generated with \[Claude Code\][^\n"']*\n?/gm,
  /(\n[ \t]*---[ \t]*)?\n[ \t]*_Generated by \[Claude Code\][^\n]*_[ \t]*/g,
  /^[ \t]*https:\/\/claude\.ai\/code\/session_[^\s"']*[ \t]*\n?/gm,
]

const strip = (s: string) => {
  const out = CUT.reduce((t, re) => t.replace(re, ''), s)
  return out === s ? s : out.replace(/\n{3,}/g, '\n\n').replace(/\s+("?)$/, '$1')
}

const clean = (v: unknown): unknown =>
  typeof v === 'string' ? strip(v)
    : Array.isArray(v) ? v.map(clean)
      : v && typeof v === 'object' ? Object.fromEntries(Object.entries(v).map(([k, x]) => [k, clean(x)]))
        : v

export const register: Register = on => {
 
  on('attribution.text', ($, e, next) => (e.kind === 'commit' || e.kind === 'pr' ? { text: '' } : next(e)))
 
  on('tool.call', ($, e, next) =>
    e.tool === 'Bash' || e.tool.startsWith('mcp__github__') ? next(clean(e) as typeof e) : next(e),
  )
}
